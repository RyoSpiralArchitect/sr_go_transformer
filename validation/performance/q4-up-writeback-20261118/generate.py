"""Use the pinned Q4 range with the same arithmetic and a different store."""

import argparse
from pathlib import Path
import subprocess


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError(f"unexpected source anchor: {old!r}")
    return text.replace(old, new, 1)


def up_ranges(runtime):
    start = runtime.index("func linearQ4TwoRowOutputPairRange(")
    end = runtime.index("\n}\n", start) + 3
    source = runtime[start:end]
    result = []
    for name, write in (("storeUpRange", True), ("localUpRange", False)):
        code = replace_once(source, "func linearQ4TwoRowOutputPairRange(job *fp32Kernel, lo, hi int) {",
                            f"func {name}(job *fp32Kernel, gate []float32, lo, hi int) {{")
        code = replace_once(code, "x, y, w := job.x, job.y, job.w",
                            "x, w := job.x, job.w\n\ty := job.y" if write else "x, w := job.x, job.w")
        pair = "y[o], y[o+1], y[out+o], y[out+o+1] = a00, a01, a10, a11"
        tail = "y[o], y[out+o] = a0, a1"
        s = "\n\t\t\t"
        act_pair = s.join(f"gate[{index}] = applyUp(gate[{index}], {var})" for index,var in
                          (("o","a00"),("o+1","a01"),("out+o","a10"),("out+o+1","a11")))
        act_tail = s.join(f"gate[{index}] = applyUp(gate[{index}], {var})" for index,var in
                          (("o","a0"),("out+o","a1")))
        code = replace_once(code, pair, (pair+s if write else "")+act_pair)
        code = replace_once(code, tail, (tail+s if write else "")+act_tail)
        result.append(code)
    return "\n".join(result)


def prefill_probe(runtime):
    start = runtime.index("func (m *Model) prefillSelected(")
    end = runtime.index("\nfunc (m *Model) Step(", start)
    code = replace_once(runtime[start:end], ") prefillSelected(ctx ", ") prefillWritebackProbe(ctx ")
    # Preserve the same attention planning, allocator and unfused paths. The
    # duplicate is a test-only body so shipping source is not instrumented.
    mark = "\t\tlinearIntoWithExecutor(executor, w.G, w.N, b.Gate, n)"
    idx = code.index(mark)
    end = code.index("\n\t\tlinearIntoWithExecutor(executor, w.Q, w.G, b.Down, n)", idx)
    guard = """\t\tif upWritebackEligible(m, b, executor, w, n) {
\t\t\tprobeUpLocal(executor, w.G, w.U, w.N, b.Gate, b.Up)
\t\t} else {
"""
    return code[:idx] + guard + "\n".join("\t"+line for line in code[idx:end].splitlines()) + "\n\t\t}" + code[end:]


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("source", type=Path)
    p.add_argument("output", type=Path)
    args = p.parse_args()
    source = args.source.read_text()
    args.output.write_text(
        "// Copyright 2026 RyoSpiralArchitect\n// SPDX-License-Identifier: Apache-2.0\n"
        "// Generated by generate.py; do not edit.\n\npackage main\n\n"
        'import ("context";"errors";"math";"runtime";"runtime/trace")\n\n' +
        up_ranges(source) + "\n" + prefill_probe(source) + "\n"
    )
    subprocess.run(["gofmt", "-w", str(args.output)], check=True, timeout=30)


if __name__ == "__main__":
    main()
