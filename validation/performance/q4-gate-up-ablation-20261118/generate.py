"""Build two interleaved block variants with the same accumulator order."""

import argparse
from pathlib import Path
import re
import subprocess


def blocks(text):
    anchor = "func dotQ4TwoRowOutputPair64("
    start = text.index(anchor)
    end = text.index("\n}\n", start) + 3
    params = "(x0, x1, u0, u1 *[64]float32, w0, w1 *[32]byte)"
    shared = text[start:end].replace("dotQ4TwoRowOutputPair64(x0, x1 *[64]float32, w0, w1 *[32]byte)",
                                      "gateUpSharedBlock" + params, 1)
    part = shared.replace("gateUpSharedBlock", "gateUpSplitBlock", 1)
    # Both blocks receive the same four activation arguments. The split
    # form reads through the two distinct argument registers for Up, so
    # common subexpression elimination cannot turn it into shared loads.
    # The caller passes the exact same activation pointers twice.
    lines = part.splitlines()
    indices = None
    statements = sites = 0
    for i, line in enumerate(lines):
        match = re.fullmatch(r"\t\tv00, v01 := x0\[(\d+)\], x0\[(\d+)\]", line)
        if match:
            indices = match.groups()
        if line.startswith("\t\tp1 :="):
            if indices is None:
                raise ValueError("the block no longer has fixed load sites")
            a, b = indices
            lines[i] = f"\t\tw00, w01 := u0[{a}], u0[{b}]\n\t\tw10, w11 := u1[{a}], u1[{b}]\n" + line
            sites += 1
        if " * p1[" in line:
            lines[i], n = re.subn(r"\bv(0[01]|1[01])\b", r"w\1", line)
            statements += n
    if (sites, statements) != (32, 128):
        raise ValueError("unexpected second-channel arithmetic")
    return shared + "\n" + "\n".join(lines) + "\n"


def ranges(template):
    text = template.read_text()
    if text.count("DOT_BLOCK(") != 1 or text.count("RANGE_FUNC(") != 1:
        raise ValueError("missing Q4 range placeholders")
    return "\n".join(text.replace("RANGE_FUNC", mode).replace("DOT_BLOCK", dot) for mode,dot in (
        ("gateUpSplitRange", "gateUpSplitBlock"), ("gateUpSharedRange", "gateUpSharedBlock")))


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("source", type=Path)
    p.add_argument("destination", type=Path)
    args = p.parse_args()
    folder = Path(__file__).resolve().parent
    args.destination.write_text(
        "// Copyright 2026 RyoSpiralArchitect\n// SPDX-License-Identifier: Apache-2.0\n"
        "// Generated by generate.py; do not edit.\n\npackage main\n\n" +
        blocks(args.source.read_text()) + "\n" + ranges(folder/"tile.go.txt")
    )
    subprocess.run(["gofmt", "-w", str(args.destination)], check=True, timeout=30)


if __name__ == "__main__":
    main()
