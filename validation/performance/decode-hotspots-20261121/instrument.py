"""Copy the frozen forward path into a timed test-only method."""

def once(src, before, after):
    if src.count(before) != 1:
        raise ValueError(f"expected one source anchor: {before!r}")
    return src.replace(before, after)


def forward(src):
    a = src.index("func (m *Model) prefillSelected(")
    b = src.index("\nfunc (m *Model) Step(", a)
    code = once(src[a:b], "prefillSelected(ctx", "hotspotPrefill(ctx")
    code = once(code, "wantLogits []bool)", "wantLogits []bool, timing *hotspotTrace)")
    for role, dst, inp, param in (
        ("query","Q","N","Q"), ("key","K","N","K"), ("value","V","N","V"), ("attnOut","Q","A","O"),
        ("gate","G","N","Gate"), ("up","U","N","Up"), ("down","Q","G","Down"),
    ):
        args = f"executor, w.{dst}, w.{inp}, b.{param}, n)"
        code = once(code, "linearIntoWithExecutor("+args, f"timing.project({role}Stage, "+args)
    args = "executor, w.Logits[:heads*c.Vocab], w.N[:heads*d], head, heads)"
    code = once(code, "linearIntoWithExecutor("+args, "timing.project(headStage, "+args)
    code = once(code, "w.attend(executor, c, l, n, attention)", """startAttention := time.Now()
		w.attend(executor, c, l, n, attention)
		timing.add(attentionStage, startAttention)
		if attention.sharedKV {
			timing.shared++
		}""")
    start_activation = "\t\t\tfor i, v := range w.G {\n\t\t\t\tw.G[i] = float32(float64(v)/(1+math.Exp(-float64(v))))"
    code = once(code, start_activation, "\t\t\tstartActivation := time.Now()\n"+start_activation)
    after_activation = "\t\t\t}\n\t\t}\n\t\ttiming.project(downStage"
    code = once(code, after_activation, "\t\t\t}\n\t\t\ttiming.add(activationStage, startActivation)\n\t\t}\n\t\ttiming.project(downStage")
    return ('// Generated by instrument.py; only the test method contains clocks.\n'
            'package main\n\nimport ("context";"errors";"math";"runtime";"runtime/trace";"time")\n\n'+code)


